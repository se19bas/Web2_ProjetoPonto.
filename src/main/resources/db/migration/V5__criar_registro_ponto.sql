CREATE TABLE registro_ponto (
                                id_registro_ponto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                id_funcionario BIGINT NOT NULL,
                                id_area_permitida BIGINT NULL,

                                data_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                tipo VARCHAR(20) NOT NULL
                                    CHECK (
                                        tipo IN (
                                                 'ENTRADA',
                                                 'SAIDA',
                                                 'INICIO_INTERVALO',
                                                 'FIM_INTERVALO'
                                            )
                                        ),

                                latitude DECIMAL(10, 8) NOT NULL,
                                longitude DECIMAL(11, 8) NOT NULL,
                                distancia_area DECIMAL(10, 2),
                                dentro_area BOOLEAN NOT NULL,

                                CONSTRAINT fk_registro_funcionario
                                    FOREIGN KEY (id_funcionario)
                                        REFERENCES funcionario (id_usuario),

                                CONSTRAINT fk_registro_area
                                    FOREIGN KEY (id_area_permitida)
                                        REFERENCES area_permitida (id_area_permitida),
);